    /**
     * Get transliteration for an Arabic word.
     * Falls back to a heuristic if word not in dictionary.
     */
    fun getTransliteration(word: String): String {
        // Try exact match first
        dictionary[word]?.let { return it.first }

        // Try without trailing punctuation
        val cleanWord = word.trimEnd(':', '.', ',', '،', '؛')
        dictionary[cleanWord]?.let { return it.first }

        // Try prefix match (for words with attached prefixes like و, ف, ب, ل)
        for (len in 2..minOf(4, word.length)) {
            val prefix = word.substring(0, len)
            val rest = word.substring(len)
            dictionary[rest]?.let { return "${prefix}+" + it.first }
        }

        // Heuristic: return as-is (Arabic) — user can still hear audio
        return "—"
    }

    /**
     * Get Bangla meaning for an Arabic word.
     * Falls back to "—" if word not in dictionary.
     */
    fun getMeaning(word: String): String {
        // Try exact match first
        dictionary[word]?.let { return it.second }

        // Try without trailing punctuation
        val cleanWord = word.trimEnd(':', '.', ',', '،', '؛')
        dictionary[cleanWord]?.let { return it.second }

        // Try prefix match
        for (len in 2..minOf(4, word.length)) {
            val rest = word.substring(len)
            dictionary[rest]?.let { return it.second }
        }

        return "—"
    }
